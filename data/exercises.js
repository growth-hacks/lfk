// Диапазон в timer ([5, 10]) — как в источнике; «цель» внутри него выбирает пользователь, по умолчанию нижняя граница.
// watch — блок «Следи»: [жирное начало, продолжение]. Только то, за чем надо следить во время упражнения:
//   ошибки, точки контроля, боль. Если это повтор описания — блока нет.
// tips — «Совет»: когда и как удобно делать, как упростить или усложнить.
// steps — свёрнутое «Описание словами».
// Тексты для кисти пока близки к формулировкам плана; их уточняет отдельная работа над текстами.
//
// timer.type:
//   (у count можно задать secPerRep — сколько секунд в среднем на повтор, для оценки времени)
//   hold    — держать hold секунд, reps раз, между повторами короткая пауза; sets подходов
//   tempo   — повторы в темпе phases [[подпись, секунды], …]; темп задан для показа, в источниках — «медленно»
//   timed   — одно задание на duration секунд
//   count   — повторы без темпа: отмечаешь сам кнопкой
//   measure — замер (тест у стены)
// sides — стороны или варианты по очереди (ноги, варианты А и Б).
// cues — откуда подсказки «Следи» и «Совет», если их нет в основном источнике (методички, памятки больниц).
//
// stages — уровни по номеру занятия курса (голеностоп). Номер занятия считает приложение по дням с отметками
// в группе программы; уровень — первый, у которого upTo ≥ номера. В уровне можно задать:
//   surface: 'floor' | 'board' (на чём стоишь), eyes: 'closed', hold: 'hand' | 'free' (держишься рукой или нет),
//   jump: 2 | 1 (прыжки на двух или на одной), band: 1–3 (какая по счёту лента), timer — замена timer на этом уровне.
// Личные замены (подушка вместо доски, свои ленты) — в profile.js, а не здесь.

